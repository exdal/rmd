#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum KeybindPreset {
    Default,
    StrongDmm,
}

impl KeybindPreset {
    pub fn bindings(self) -> KeyBindings {
        match self {
            Self::Default => KeyBindings::default(),
            Self::StrongDmm => KeyBindings::strong_dmm(),
        }
    }
}

